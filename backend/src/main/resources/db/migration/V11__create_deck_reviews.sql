CREATE TABLE deck_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    deck_id BIGINT NOT NULL,
    rating INTEGER NOT NULL,
    comment VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_deck_reviews_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_deck_reviews_deck FOREIGN KEY (deck_id) REFERENCES decks(id) ON DELETE CASCADE,
    CONSTRAINT uq_deck_reviews_user_deck UNIQUE (user_id, deck_id),
    CONSTRAINT chk_deck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT chk_deck_reviews_comment CHECK (comment IS NULL OR comment ~ '[^[:space:]]')
);

CREATE INDEX idx_deck_reviews_deck_created_at ON deck_reviews(deck_id, created_at DESC, id DESC);
