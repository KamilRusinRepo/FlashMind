CREATE TABLE user_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    type VARCHAR(32) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_user_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_user_tokens_hash UNIQUE (token_hash),
    CONSTRAINT chk_user_tokens_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_user_tokens_type CHECK (type IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET')),
    CONSTRAINT chk_user_tokens_expiry CHECK (expires_at > created_at),
    CONSTRAINT chk_user_tokens_usage CHECK (used_at IS NULL OR (used_at >= created_at AND used_at < expires_at))
);

CREATE INDEX idx_user_tokens_user_type ON user_tokens (user_id, type);
