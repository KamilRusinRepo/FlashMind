CREATE TABLE flashcards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_id BIGINT NOT NULL,
    question VARCHAR(2000) NOT NULL,
    answer VARCHAR(2000) NOT NULL,
    example_sentence VARCHAR(1000),
    translated_example VARCHAR(1000),
    image_url VARCHAR(2048),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_flashcards_deck FOREIGN KEY (deck_id) REFERENCES decks (id) ON DELETE CASCADE,
    CONSTRAINT chk_flashcards_question CHECK (question ~ '[^[:space:]]'),
    CONSTRAINT chk_flashcards_answer CHECK (answer ~ '[^[:space:]]')
);

CREATE INDEX idx_flashcards_deck_created_at ON flashcards (deck_id, created_at DESC, id DESC);
