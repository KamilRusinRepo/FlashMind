ALTER TABLE users ADD COLUMN daily_reminders_enabled BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE daily_reminder_dispatches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reminder_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    published_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    CONSTRAINT uq_daily_reminder_user_date UNIQUE(user_id, reminder_date),
    CONSTRAINT chk_daily_reminder_status CHECK (
        (status = 'PENDING' AND published_at IS NULL AND sent_at IS NULL)
        OR (status = 'PUBLISHED' AND published_at IS NOT NULL AND sent_at IS NULL)
        OR (status = 'SENT' AND sent_at IS NOT NULL)
        OR (status = 'SKIPPED' AND sent_at IS NULL)
    ),
    CONSTRAINT chk_daily_reminder_dates CHECK (
        (published_at IS NULL OR published_at >= created_at) AND (sent_at IS NULL OR sent_at >= created_at)
    )
);
CREATE INDEX idx_daily_reminder_pending ON daily_reminder_dispatches(status, id);
