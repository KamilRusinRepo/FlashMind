CREATE TABLE decks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    deck_type VARCHAR(20) NOT NULL,
    source_language VARCHAR(60) NOT NULL,
    target_language VARCHAR(60),
    category VARCHAR(60),
    background_url TEXT,
    is_public BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_decks_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_decks_name CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT chk_decks_source_language CHECK (source_language ~ '[^[:space:]]'),
    CONSTRAINT chk_decks_type CHECK (deck_type IN ('GENERAL', 'LANGUAGE')),
    CONSTRAINT chk_decks_target_language CHECK (
        (deck_type = 'GENERAL' AND target_language IS NULL)
        OR (deck_type = 'LANGUAGE' AND target_language IS NOT NULL AND target_language ~ '[^[:space:]]')
    )
);

CREATE INDEX idx_decks_owner_created_at ON decks (owner_id, created_at DESC, id DESC);
