CREATE TABLE study_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    deck_id BIGINT NOT NULL,
    total_cards INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    CONSTRAINT fk_study_sessions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_study_sessions_deck FOREIGN KEY (deck_id) REFERENCES decks (id) ON DELETE CASCADE,
    CONSTRAINT chk_study_sessions_total CHECK (total_cards > 0),
    CONSTRAINT chk_study_sessions_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'ABANDONED')),
    CONSTRAINT chk_study_sessions_end CHECK (
        (status = 'ACTIVE' AND ended_at IS NULL)
        OR (status IN ('COMPLETED', 'ABANDONED') AND ended_at IS NOT NULL AND ended_at >= started_at)
    )
);

CREATE INDEX idx_study_sessions_user_started ON study_sessions (user_id, started_at DESC, id DESC);
CREATE INDEX idx_study_sessions_deck ON study_sessions (deck_id);

CREATE TABLE study_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    flashcard_id BIGINT,
    position INTEGER NOT NULL,
    question_snapshot VARCHAR(2000) NOT NULL,
    answer_snapshot VARCHAR(2000) NOT NULL,
    example_sentence_snapshot VARCHAR(1000),
    translated_example_snapshot VARCHAR(1000),
    image_url_snapshot VARCHAR(2048),
    user_answer VARCHAR(2000),
    was_correct BOOLEAN,
    used_hint BOOLEAN NOT NULL DEFAULT FALSE,
    skipped BOOLEAN NOT NULL DEFAULT FALSE,
    answered_at TIMESTAMPTZ,
    CONSTRAINT fk_study_answers_session FOREIGN KEY (session_id) REFERENCES study_sessions (id) ON DELETE CASCADE,
    CONSTRAINT fk_study_answers_flashcard FOREIGN KEY (flashcard_id) REFERENCES flashcards (id) ON DELETE SET NULL,
    CONSTRAINT uq_study_answers_position UNIQUE (session_id, position),
    CONSTRAINT uq_study_answers_flashcard UNIQUE (session_id, flashcard_id),
    CONSTRAINT chk_study_answers_position CHECK (position > 0),
    CONSTRAINT chk_study_answers_question CHECK (question_snapshot ~ '[^[:space:]]'),
    CONSTRAINT chk_study_answers_expected_answer CHECK (answer_snapshot ~ '[^[:space:]]'),
    CONSTRAINT chk_study_answers_state CHECK (
        (answered_at IS NULL AND was_correct IS NULL AND user_answer IS NULL AND NOT skipped)
        OR (answered_at IS NOT NULL AND was_correct IS NOT NULL AND user_answer IS NOT NULL
            AND (NOT skipped OR (NOT was_correct AND user_answer = '')))
    )
);

CREATE INDEX idx_study_answers_flashcard ON study_answers (flashcard_id);

CREATE TABLE flashcard_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    flashcard_id BIGINT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    correct_count INTEGER NOT NULL DEFAULT 0,
    wrong_count INTEGER NOT NULL DEFAULT 0,
    mastery_level INTEGER NOT NULL DEFAULT 0,
    wrong_streak INTEGER NOT NULL DEFAULT 0,
    last_answered_at TIMESTAMPTZ,
    next_review_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_flashcard_progress_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_flashcard_progress_flashcard FOREIGN KEY (flashcard_id) REFERENCES flashcards (id) ON DELETE CASCADE,
    CONSTRAINT uq_flashcard_progress_user_card UNIQUE (user_id, flashcard_id),
    CONSTRAINT chk_flashcard_progress_counts CHECK (
        attempts >= 0 AND correct_count >= 0 AND wrong_count >= 0 AND attempts = correct_count + wrong_count
    ),
    CONSTRAINT chk_flashcard_progress_mastery CHECK (mastery_level BETWEEN 0 AND 4),
    CONSTRAINT chk_flashcard_progress_wrong_streak CHECK (wrong_streak >= 0),
    CONSTRAINT chk_flashcard_progress_dates CHECK (
        (attempts = 0 AND last_answered_at IS NULL AND next_review_at IS NULL)
        OR (attempts > 0 AND last_answered_at IS NOT NULL AND next_review_at IS NOT NULL AND next_review_at >= last_answered_at)
    )
);

CREATE INDEX idx_flashcard_progress_user_review ON flashcard_progress (user_id, next_review_at, flashcard_id);
CREATE INDEX idx_flashcard_progress_flashcard ON flashcard_progress (flashcard_id);
